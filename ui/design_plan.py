"""Design Plan Page: browse the generated hardware plan and unified design context."""

from __future__ import annotations

import json
import streamlit as st


def render() -> None:
    st.title("📋 Hardware Design Plan & Specification")
    st.caption("Inspect the structured submodule plan, bus mappings, intermediate Unified Design Context, and the component RTL Generation Plan.")

    if "design_results" not in st.session_state:
        st.info("💡 No active design results found in this session. Head to the **Hardware Design** page to start a new generation.")
        return

    results = st.session_state["design_results"]
    plan = results.get("plan", {})
    design_spec = results.get("design_spec", "")

    # Retrieve component-level RTL Generation Plan
    rtl_plan = results.get("rtl_generation_plan")
    if not rtl_plan:
        outputs = results.get("outputs", {})
        for target_data in outputs.values():
            if isinstance(target_data, dict) and target_data.get("plan"):
                rtl_plan = target_data["plan"]
                break
    if not rtl_plan and isinstance(plan, dict) and ("ports" in plan or "internal_registers" in plan):
        rtl_plan = plan

    tab_spec, tab_plan, tab_rtl = st.tabs([
        "📄 Unified Design Specification",
        "🏗️ Hardware Architecture Plan",
        "📐 Component RTL Generation Plan"
    ])

    with tab_spec:
        st.markdown("### Unified Design Context Specification")
        st.caption("Consolidated single-source-of-truth document containing requirements, architecture plan, and protocol constraints.")
        st.markdown(design_spec or "No specification text generated.")

    with tab_plan:
        st.markdown("### Hardware Architecture Plan")
        st.caption("Structured planning schema generated by the planning agent.")
        
        st.markdown(f"**System Architecture Overview:** {plan.get('system_architecture', 'N/A')}")
        st.markdown(f"**Registers Summary:** {plan.get('registers_summary', 'N/A')}")
        st.markdown(f"**Memories Summary:** {plan.get('memories_summary', 'N/A')}")
        
        st.divider()
        col1, col2 = st.columns(2)
        
        with col1:
            st.subheader("Submodules Hierarchy")
            submodules = plan.get("submodules", [])
            if submodules:
                for sub in submodules:
                    with st.container(border=True):
                        st.markdown(f"**Module:** `{sub.get('name', 'N/A')}`")
                        st.write(f"Purpose: {sub.get('purpose', 'N/A')}")
                        st.write(f"Ports: {', '.join(sub.get('interfaces', []))}")
            else:
                st.caption("No submodules defined in architecture plan.")
                    
        with col2:
            st.subheader("Clock & Reset Domains")
            clock_domains = plan.get("clock_domains", [])
            if clock_domains:
                for clk in clock_domains:
                    with st.container(border=True):
                        st.markdown(f"**Clock:** `{clk.get('name', 'N/A')}`")
                        st.write(f"Reset: {clk.get('reset_strategy', 'N/A')}")
                        st.write(f"Description: {clk.get('description', 'N/A')}")
            else:
                st.caption("No clock domains defined in architecture plan.")

        st.divider()
        st.subheader("FSM Architecture")
        fsm = plan.get("fsm_architecture", {})
        st.write(fsm.get("description", ""))
        
        states = fsm.get("states", [])
        if states:
            fsm_cols = st.columns(len(states))
            for idx, state in enumerate(states):
                with fsm_cols[idx % len(fsm_cols)]:
                    with st.container(border=True):
                        st.markdown(f"**State:** `{state.get('name', 'N/A')}`")
                        st.caption(state.get("actions", ""))

    with tab_rtl:
        st.markdown("### 📐 Target Component RTL Generation Plan")
        st.caption("Deterministic implementation contract defining I/O ports, registers, sequential processes, combinational logic, and provenance.")

        if not rtl_plan:
            st.info("ℹ️ No component-level RTL Generation Plan generated yet in this session. Generate RTL from the **Hardware Design** page.")
        else:
            # Metadata & Overview Cards
            mod_name = rtl_plan.get("module_name", "N/A")
            target_comp = rtl_plan.get("target_component_id", "N/A")
            fsm_strat = rtl_plan.get("fsm_strategy", "N/A")
            lang = rtl_plan.get("target_language", "Verilog")

            c1, c2, c3, c4 = st.columns(4)
            c1.metric("Module Name", str(mod_name))
            c2.metric("Target Component", str(target_comp))
            c3.metric("FSM Strategy", str(fsm_strat))
            c4.metric("Target Language", str(lang))

            st.divider()

            # 1. Ports Table
            st.subheader("🔌 Module Port Interface")
            ports = rtl_plan.get("ports", [])
            if ports:
                port_data = []
                for p in ports:
                    if isinstance(p, dict):
                        port_data.append({
                            "Port Name": p.get("name", ""),
                            "Direction": p.get("direction", ""),
                            "Width": p.get("width", 1),
                            "Reset Value": p.get("reset_value") if p.get("reset_value") is not None else "N/A",
                            "Clock Domain": p.get("clock_domain", "N/A"),
                            "Origin": p.get("origin", "INHERITED"),
                            "Description": p.get("description", "")[:50]
                        })
                st.dataframe(port_data, use_container_width=True, hide_index=True)
            else:
                st.caption("No ports defined.")

            # 2. Parameters
            params = rtl_plan.get("parameters", [])
            if params:
                st.subheader("⚙️ Module Parameters / Generics")
                param_data = []
                for p in params:
                    if isinstance(p, dict):
                        param_data.append({
                            "Parameter Name": p.get("name", ""),
                            "Type": p.get("param_type", "integer"),
                            "Default Value": p.get("default_value", ""),
                            "Origin": p.get("origin", "INHERITED"),
                            "Description": p.get("description", "")
                        })
                st.dataframe(param_data, use_container_width=True, hide_index=True)

            # 3. Internal Registers
            regs = rtl_plan.get("internal_registers", [])
            if regs:
                st.subheader("💾 Internal Registers & State Variables")
                reg_data = []
                for r in regs:
                    if isinstance(r, dict):
                        reg_data.append({
                            "Register Name": r.get("name", ""),
                            "Width": r.get("width", 1),
                            "Reset Value": r.get("reset_value", "0"),
                            "Clock": r.get("clock", "clk"),
                            "Reset": r.get("reset", "rst_n"),
                            "Origin": r.get("origin", "INHERITED"),
                            "Description": r.get("description", "")
                        })
                st.dataframe(reg_data, use_container_width=True, hide_index=True)

            # 4. Sequential Processes & Logic
            seq_logic = rtl_plan.get("sequential_logic", [])
            if seq_logic:
                st.subheader("⏱️ Sequential Logic Directives")
                seq_data = []
                for s in seq_logic:
                    if isinstance(s, dict):
                        seq_data.append({
                            "Process Name": s.get("process_name", "proc"),
                            "Clock Signal": s.get("clock_signal", "clk"),
                            "Reset Signal": s.get("reset_signal", "rst_n"),
                            "Target Register": s.get("target_register", "N/A"),
                            "Reset Assignment": s.get("reset_assignment", "N/A"),
                            "Next-State Logic": s.get("next_state_expression", "N/A"),
                            "Origin": s.get("origin", "INHERITED")
                        })
                st.dataframe(seq_data, use_container_width=True, hide_index=True)

            # 5. Combinational Logic Directives
            comb_logic = rtl_plan.get("combinational_logic", [])
            if comb_logic:
                st.subheader("🔀 Combinational Logic Directives")
                comb_data = []
                for c in comb_logic:
                    if isinstance(c, dict):
                        comb_data.append({
                            "Process Name": c.get("process_name", "comb_proc"),
                            "Target Signal": c.get("target_signal", "N/A"),
                            "Expression": c.get("expression", "N/A"),
                            "Condition": c.get("condition") or "always",
                            "Origin": c.get("origin", "INHERITED")
                        })
                st.dataframe(comb_data, use_container_width=True, hide_index=True)

            # 6. FSMs
            fsms = rtl_plan.get("fsms", [])
            if fsms:
                st.subheader("🔄 Finite State Machines (FSMs)")
                for fsm_item in fsms:
                    if isinstance(fsm_item, dict):
                        with st.container(border=True):
                            st.markdown(f"**FSM:** `{fsm_item.get('name', 'fsm')}` (State Reg: `{fsm_item.get('state_register', 'state')}` | Reset: `{fsm_item.get('reset_state', 'IDLE')}`)")
                            st.write(f"**States:** {', '.join(fsm_item.get('states', []))}")
                            transitions = fsm_item.get("transitions", [])
                            if transitions:
                                trans_rows = []
                                for t in transitions:
                                    if isinstance(t, dict):
                                        trans_rows.append({
                                            "From State": t.get("from_state", ""),
                                            "To State": t.get("to_state", ""),
                                            "Condition": t.get("condition", ""),
                                            "Actions": t.get("actions", "")
                                        })
                                st.dataframe(trans_rows, use_container_width=True, hide_index=True)

            # 7. Unresolved Logic & Specification Gaps
            unresolved = rtl_plan.get("unresolved_logic", [])
            if unresolved:
                st.warning("⚠️ Specification Gaps / Unresolved Logic Directives:")
                for un in unresolved:
                    if isinstance(un, dict):
                        with st.container(border=True):
                            st.markdown(f"**Target:** `{un.get('target_signal', 'signal')}` ({un.get('logic_type', 'logic')})")
                            st.caption(f"Reason: {un.get('reason', '')} | Fallback: {un.get('fallback_behavior', '')}")

            # 8. Interactive JSON & Download
            st.divider()
            with st.expander("🔍 Complete RTL Generation Plan (Raw JSON)", expanded=False):
                json_str = json.dumps(rtl_plan, indent=2)
                st.download_button(
                    label="💾 Download Plan JSON",
                    data=json_str,
                    file_name=f"{mod_name}_rtl_plan.json",
                    mime="application/json",
                    key="dl_rtl_plan_json"
                )
                st.json(rtl_plan)
